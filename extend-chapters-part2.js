const fs = require('fs');

function appendText(chFile, additionalText) {
  const current = fs.readFileSync(chFile, 'utf8');
  fs.writeFileSync(chFile, current.trim() + '\n\n' + additionalText.trim() + '\n', 'utf8');
}

